import { useEffect, useState } from 'react';
import toast from 'react-hot-toast';
import { api, apiError } from '../lib/api';
import { fmtDate, fmtNumber, initials } from '../lib/format';
import StatCard from '../components/StatCard';

export default function Admin() {
  const [stats, setStats] = useState(null);
  const [users, setUsers] = useState([]);

  useEffect(() => {
    api.get('/admin/stats').then(({ data }) => setStats(data)).catch((error) => toast.error(apiError(error)));
    api.get('/admin/users').then(({ data }) => setUsers(data)).catch(() => setUsers([]));
  }, []);

  return (
    <div className="space-y-6">
      <div>
        <p className="text-xs font-semibold uppercase tracking-wider text-indigo-600">Admin</p>
        <h1 className="mt-1 text-2xl font-bold tracking-tight text-slate-900">Platform overview</h1>
        <p className="mt-1 text-sm text-slate-500">Aggregate usage across every account.</p>
      </div>

      <section className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
        <StatCard label="Users" value={fmtNumber(stats?.users)} hint="registered accounts" />
        <StatCard label="Documents" value={fmtNumber(stats?.documents)} hint={`${fmtNumber(stats?.chunks)} passages`} accent="emerald" />
        <StatCard label="Conversations" value={fmtNumber(stats?.sessions)} hint={`${fmtNumber(stats?.questions)} questions`} accent="amber" />
        <StatCard
          label="Avg answer time"
          value={`${fmtNumber(Math.round(stats?.avgLatencyMs || 0))} ms`}
          hint={`${fmtNumber(stats?.aiAnswers)} AI · ${fmtNumber(stats?.offlineAnswers)} offline`}
          accent="slate"
        />
      </section>

      <section className="card flex flex-wrap items-center justify-between gap-3 p-4">
        <div>
          <p className="text-sm font-semibold text-slate-900">Answer engine</p>
          <p className="text-xs text-slate-500">
            {stats?.aiConfigured
              ? 'A Gemini key is configured, so answers are generated by the model from retrieved passages.'
              : 'No AI key is configured. Answers are quoted from retrieved passages (offline mode).'}
          </p>
        </div>
        <span
          className={`chip ${
            stats?.aiConfigured ? 'bg-indigo-50 text-indigo-700' : 'bg-amber-50 text-amber-700'
          }`}
        >
          {stats?.aiConfigured ? 'AI enabled' : 'Offline mode'}
        </span>
      </section>

      <section className="card overflow-hidden">
        <div className="border-b border-slate-100 px-5 py-3">
          <h2 className="text-sm font-semibold uppercase tracking-wider text-slate-500">Users</h2>
        </div>
        <div className="overflow-x-auto">
          <table className="w-full text-left text-sm">
            <thead className="bg-slate-50 text-[11px] uppercase tracking-wider text-slate-500">
              <tr>
                <th className="px-5 py-2.5 font-semibold">User</th>
                <th className="px-3 py-2.5 font-semibold">Role</th>
                <th className="px-3 py-2.5 text-right font-semibold">Documents</th>
                <th className="px-3 py-2.5 text-right font-semibold">Chats</th>
                <th className="px-5 py-2.5 font-semibold">Joined</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {users.length === 0 ? (
                <tr>
                  <td colSpan={5} className="px-5 py-8 text-center text-sm text-slate-500">
                    No users yet.
                  </td>
                </tr>
              ) : (
                users.map((user) => (
                  <tr key={user.id} className="hover:bg-slate-50/60">
                    <td className="px-5 py-3">
                      <div className="flex items-center gap-2.5">
                        <span className="flex h-8 w-8 items-center justify-center rounded-lg bg-slate-900 text-[11px] font-bold text-white">
                          {initials(user.name)}
                        </span>
                        <span>
                          <span className="block font-medium text-slate-800">{user.name}</span>
                          <span className="block text-xs text-slate-500">{user.email}</span>
                        </span>
                      </div>
                    </td>
                    <td className="px-3 py-3">
                      <span
                        className={`chip ${
                          user.role === 'ADMIN' ? 'bg-indigo-50 text-indigo-700' : 'bg-slate-100 text-slate-600'
                        }`}
                      >
                        {user.role}
                      </span>
                    </td>
                    <td className="px-3 py-3 text-right text-slate-700">{fmtNumber(user.documents)}</td>
                    <td className="px-3 py-3 text-right text-slate-700">{fmtNumber(user.sessions)}</td>
                    <td className="px-5 py-3 text-xs text-slate-500">{fmtDate(user.createdAt)}</td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </section>
    </div>
  );
}
